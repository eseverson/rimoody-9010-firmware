#!/usr/bin/env python3
"""Rasterize miata.svg into an LVGL A8 image (an alpha mask: the logo's black strokes become opaque, the white
background transparent), so the UI can draw it in any colour, white on black for the home screen.

  mklogo.py [--width 640] [--svg miata.svg] [--out isp/sd-10-net/ui_logo.c]

Needs ImageMagick (`magick`). Regenerate after changing the SVG; the output is committed."""
import argparse, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')

ap = argparse.ArgumentParser()
ap.add_argument('--width', type=int, default=640)
ap.add_argument('--svg', default=os.path.join(ROOT, 'miata.svg'))
ap.add_argument('--out', default=os.path.join(ROOT, 'isp', 'sd-10-net', 'ui_logo.c'))
a = ap.parse_args()

# render big, trim the white margin, scale to the target height, 8-bit grey
r = subprocess.run(['magick', '-density', '600', a.svg, '-background', 'white', '-flatten', '-trim', '+repage',
                    '-resize', '%d' % a.width, '-colorspace', 'Gray', '-depth', '8', 'gray:-'], capture_output=True)
if r.returncode:
    sys.exit(r.stderr.decode())
grey = r.stdout
ident = subprocess.run(['magick', '-density', '600', a.svg, '-background', 'white', '-flatten', '-trim', '+repage',
                        '-resize', '%d' % a.width, '-format', '%w %h', 'info:'], capture_output=True, text=True)
w, h = map(int, ident.stdout.split())
if len(grey) != w * h:
    sys.exit('unexpected raster size %d for %dx%d' % (len(grey), w, h))
alpha = bytes(255 - g for g in grey)   # black stroke -> opaque

with open(a.out, 'w') as f:
    f.write('/* Generated by tools/mklogo.py from miata.svg: %dx%d A8 alpha mask (draw it recoloured). */\n' % (w, h))
    f.write('#include "lvgl.h"\n\nstatic const unsigned char logo_a8[%d] = {\n' % len(alpha))
    for i in range(0, len(alpha), 24):
        f.write('    ' + ', '.join('0x%02x' % b for b in alpha[i:i + 24]) + ',\n')
    f.write('};\n\nconst lv_image_dsc_t ui_logo = {\n')
    f.write('    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = %d, .h = %d, .stride = %d },\n' % (w, h, w))
    f.write('    .data_size = sizeof(logo_a8),\n    .data = logo_a8,\n};\n')
print('%s: %dx%d A8, %d bytes' % (a.out, w, h, len(alpha)))
