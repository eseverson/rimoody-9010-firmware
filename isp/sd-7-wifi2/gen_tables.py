#!/usr/bin/env python3
"""Emit rtl8188f_tables.h: the RTL8188FU MAC/BB/AGC/RF init tables, copied verbatim from Linux
drivers/net/wireless/realtek/rtl8xxxu/rtl8xxxu_8188f.c (v6.6) so nothing is retyped by hand.

Usage: gen_tables.py <rtl8xxxu_8188f.c> <out.h>
Each table keeps its Linux terminator ({0xffff, 0xff}, {0xffff, 0xffffffff} or {0xff, 0xffffffff})."""
import re, sys

src, out = sys.argv[1:3]
text = open(src).read()

# name in Linux -> (C struct type in wifi2.c, expected terminator)
TABLES = [
    ('rtl8188f_mac_init_table', 'reg8val', (0xffff, 0xff)),
    ('rtl8188fu_phy_init_table', 'reg32val', (0xffff, 0xffffffff)),
    ('rtl8188f_agc_table', 'reg32val', (0xffff, 0xffffffff)),
    ('rtl8188fu_radioa_init_table', 'rfregval', (0xff, 0xffffffff)),
    ('rtl8188fu_cut_b_radioa_init_table', 'rfregval', (0xff, 0xffffffff)),
]

lines = ['/* Generated by gen_tables.py from Linux v6.6 rtl8xxxu_8188f.c -- do not edit. */']
for name, ctype, term in TABLES:
    m = re.search(r'static const struct rtl8xxxu_\w+ %s\[\] = \{(.*?)\n\};' % name, text, re.S)
    if not m:
        sys.exit('table %s not found' % name)
    pairs = [(int(a, 16), int(b, 16)) for a, b in re.findall(r'\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}', m.group(1))]
    if not pairs or pairs[-1] != term or term in pairs[:-1]:
        sys.exit('table %s: bad terminator' % name)
    lines.append('static const struct %s %s[] = {   /* %d entries */' % (ctype, name, len(pairs) - 1))
    w = 4 if ctype == 'reg8val' else 2
    for i in range(0, len(pairs), w):
        fmt = '{0x%03x, 0x%02x}' if ctype == 'reg8val' else '{0x%03x, 0x%08x}'
        lines.append('    ' + ', '.join(fmt % p for p in pairs[i:i + w]) + ',')
    lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
