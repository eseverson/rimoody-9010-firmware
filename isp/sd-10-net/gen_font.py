#!/usr/bin/env python3
"""Emit font8x16.h: printable ASCII (0x20-0x7E) plus a fallback box glyph from a PSF1 console font with a Unicode table.

Source used: LatGrkCyr-8x16.psfu.gz from the kbd package (Fedora: /usr/lib/kbd/consolefonts/), Ken Moffat's "sigma"
8x16 font. Its README.LatGrkCyr says: "The font is public domain, the other items are under BSD-style licenses."

Usage: gen_font.py <font.psfu.gz> <out.h>"""
import gzip, struct, sys

src, out = sys.argv[1:3]
d = gzip.open(src).read() if src.endswith('.gz') else open(src, 'rb').read()
if d[:2] != b'\x36\x04':
    sys.exit('not a PSF1 font')
mode, size = d[2], d[3]
if size != 16 or not mode & 2:
    sys.exit('need an 8x16 PSF1 font with a Unicode table')
n = 512 if mode & 1 else 256
glyphs = [d[4 + i * 16:4 + i * 16 + 16] for i in range(n)]
uni = {}
p, g = 4 + n * 16, 0
while g < n and p + 1 < len(d):
    v, = struct.unpack_from('<H', d, p)
    p += 2
    if v == 0xFFFF:
        g += 1
    elif v != 0xFFFE:
        uni.setdefault(v, g)
rows = ['/* Generated by gen_font.py from %s (public domain, see gen_font.py) -- do not edit.' % src.split('/')[-1],
        ' * 96 glyphs, 8x16, one byte per row, MSB = leftmost pixel: ASCII 0x20-0x7E, then a box for anything else. */',
        'static const unsigned char font8x16[96][16] = {']
for c in range(0x20, 0x7F):
    if c not in uni:
        sys.exit('font has no glyph for %r' % chr(c))
    rows.append('    { %s },   /* %r */' % (', '.join('0x%02x' % b for b in glyphs[uni[c]]), chr(c)))
box = bytes([0x00, 0x00, 0x7e, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7e, 0x00, 0x00, 0x00, 0x00])
rows.append('    { %s },   /* fallback box */' % ', '.join('0x%02x' % b for b in box))
rows.append('};')
open(out, 'w').write('\n'.join(rows).replace("'\\\\'", "backslash").replace("'*/'", "star slash") + '\n')
