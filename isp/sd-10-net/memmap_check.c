/* Compile-time checks of memmap.h: the regions are in address order, do not overlap, stay below U-Boot, and the
 * configured sizes of the RTOS and LVGL heaps match their slots. Generates no code. */
#include "memmap.h"
#include "FreeRTOSConfig.h"
#include "lv_conf.h"

#define BELOW(a, a_sz, b) _Static_assert((a) + (a_sz) <= (b), #a " runs into " #b)

BELOW(MM_VDEC_EVB, MM_VDEC_EVB_SZ, MM_VDEC_SPMP);
BELOW(MM_VDEC_SPMP, MM_VDEC_SPMP_SZ, MM_VDEC_SCS);
BELOW(MM_VDEC_SCS, MM_VDEC_SCS_SZ, MM_VDEC_WORK_3B);
BELOW(MM_VDEC_WORK_3B, MM_VDEC_WORK_SZ, MM_VDEC_WORK_3C);
BELOW(MM_VDEC_WORK_3C, MM_VDEC_WORK_SZ, MM_VDEC_SLOTS);
BELOW(MM_VDEC_SLOTS, MM_VDEC_SLOTS_SZ, MM_OSDVID_BUF0);
BELOW(MM_OSDVID_BUF0, MM_OSDVID_BUF_SZ, MM_OSDVID_BUF1);
BELOW(MM_OSDVID_BUF1, MM_OSDVID_BUF_SZ, MM_HELLO);
BELOW(MM_HELLO, MM_HELLO_SZ, MM_MCU_RX);
BELOW(MM_MCU_RX, MM_MCU_RX_SZ, MM_PAYLOAD);
BELOW(MM_PAYLOAD, MM_PAYLOAD_SZ, MM_LOG);
BELOW(MM_LOG, MM_LOG_SZ, MM_LOG_BOUNCE);
BELOW(MM_LOG_BOUNCE, MM_LOG_BOUNCE_SZ, MM_PREV_LOG);
BELOW(MM_PREV_LOG, MM_PREV_LOG_SZ, MM_BIGBSS);
BELOW(MM_BIGBSS, MM_BIGBSS_SZ, MM_CRASH);
BELOW(MM_CRASH, MM_CRASH_SZ, MM_HU1_REPLY);
BELOW(MM_HU1_REPLY, MM_HU1_REPLY_SZ, MM_WIFI_TXT);
BELOW(MM_WIFI_TXT, MM_WIFI_TXT_SZ, MM_RTOS_HEAP);
BELOW(MM_RTOS_HEAP, MM_RTOS_HEAP_SZ, MM_DSP);
BELOW(MM_DSP, MM_DSP_SZ, MM_LVGL_HEAP);
BELOW(MM_LVGL_HEAP, MM_LVGL_HEAP_SZ, MM_LVGL_DRAW);
BELOW(MM_LVGL_DRAW, MM_LVGL_DRAW_SZ, MM_TRAMP);
BELOW(MM_TRAMP, MM_TRAMP_SZ, MM_UPLOAD);
BELOW(MM_UPLOAD, MM_UPLOAD_SZ, MM_FB);
BELOW(MM_FB, MM_FB_SZ, MM_FB_HDR);
BELOW(MM_FB_HDR, MM_HDR_SZ, MM_UBOOT);
_Static_assert(MM_FB_HDR + 0x80 <= MM_OSDVID_HDR && MM_OSDVID_HDR + 0x80 <= MM_FB_HDR + MM_HDR_SZ, "OSD headers");
_Static_assert(MM_CRASH < MM_CRUMB && MM_CRUMB + 0x40 <= MM_VECTORS && MM_VECTORS + 0x200 <= MM_CRASH + MM_CRASH_SZ,
               "crash record, breadcrumbs, vectors");
_Static_assert((MM_VECTORS & 0xffff) == 0, "IVB.IVBASE needs 64 KB alignment");
_Static_assert(MM_UBOOT < MM_DRAM_END, "U-Boot reserve");
_Static_assert(configTOTAL_HEAP_SIZE == MM_RTOS_HEAP_SZ, "FreeRTOS heap size vs MM_RTOS_HEAP_SZ");
_Static_assert(LV_MEM_ADR == MM_LVGL_HEAP && LV_MEM_SIZE == MM_LVGL_HEAP_SZ, "lv_conf.h heap vs MM_LVGL_HEAP");
